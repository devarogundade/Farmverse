import { camel, literal, pascal, xml } from './naming';

/**
 * JSON Schema (as produced by `z.toJSONSchema` over the contract registry) → C#.
 *
 * The emitter supports exactly the subset the contracts use and refuses anything
 * else with an error that names the contract and the property, so an
 * unsupported schema is a build failure rather than silently wrong C#.
 *
 * Generated C# rules:
 *   - no reflection: every type has explicit ToWire() / FromWire(object)
 *   - string enums get `Unknown = 0` so old clients survive new values
 *   - unions on `kind` become an abstract base class + sealed variants
 *   - integers become `int` when their bounds fit 32 bits, otherwise `long`
 */

export interface JsonSchema {
  readonly $ref?: string;
  readonly type?: string | readonly string[];
  readonly const?: unknown;
  readonly enum?: readonly unknown[];
  readonly properties?: Readonly<Record<string, JsonSchema>>;
  readonly required?: readonly string[];
  readonly additionalProperties?: JsonSchema | boolean;
  readonly items?: JsonSchema;
  readonly oneOf?: readonly JsonSchema[];
  readonly anyOf?: readonly JsonSchema[];
  readonly minimum?: number;
  readonly maximum?: number;
  readonly description?: string;
}

export interface ContractDoc {
  readonly id: string;
  readonly description?: string;
}

type Ref =
  | { readonly kind: 'string'; readonly constValue?: string }
  | { readonly kind: 'int' }
  | { readonly kind: 'long' }
  | { readonly kind: 'double' }
  | { readonly kind: 'bool' }
  | { readonly kind: 'any' }
  | { readonly kind: 'enum'; readonly name: string }
  | { readonly kind: 'object'; readonly name: string }
  | { readonly kind: 'union'; readonly name: string }
  | { readonly kind: 'list'; readonly item: Ref }
  | { readonly kind: 'map'; readonly value: Ref };

interface Property {
  readonly wireName: string;
  readonly csName: string;
  readonly ref: Ref;
  readonly required: boolean;
  readonly nullable: boolean;
  readonly description?: string;
}

const INT32_MIN = -2147483648;
const INT32_MAX = 2147483647;

export const HEADER = [
  '// <auto-generated>',
  '//     Generated by contracts/codegen from the zod contracts in contracts/src.',
  '//     Do not edit: change the contract and run `npm run contracts:gen`.',
  '// </auto-generated>',
  '#nullable enable',
].join('\n');

export class CSharpEmitter {
  private readonly unionOfVariant = new Map<string, string>();
  private readonly discriminatorOfUnion = new Map<string, string>();

  constructor(
    private readonly schemas: Readonly<Record<string, JsonSchema>>,
    private readonly docs: ReadonlyMap<string, ContractDoc>,
    private readonly namespace: string,
  ) {
    for (const [id, schema] of Object.entries(schemas)) {
      if (schema.oneOf) {
        this.indexUnion(id, schema.oneOf);
      }
    }
  }

  /** Emit one file per contract: `fileName → contents`. */
  emitAll(): Map<string, string> {
    const files = new Map<string, string>();
    for (const id of Object.keys(this.schemas)) {
      files.set(`${id}.g.cs`, this.emit(id));
    }
    return files;
  }

  private emit(id: string): string {
    const schema = this.schema(id);
    let body: string;
    if (this.isStringEnum(schema)) {
      body = this.emitEnum(id, schema);
    } else if (schema.oneOf) {
      body = this.emitUnion(id, schema.oneOf);
    } else if (this.isObject(schema)) {
      body = this.emitObject(id, schema);
    } else {
      throw new Error(`Contract '${id}' is neither an object, a string enum nor a union.`);
    }
    return `${HEADER}\nusing System.Collections.Generic;\n\nnamespace ${this.namespace}\n{\n${body}}\n`;
  }

  // ------------------------------------------------------------------------
  // enums
  // ------------------------------------------------------------------------

  private emitEnum(id: string, schema: JsonSchema): string {
    const values = (schema.enum ?? []) as string[];
    const members = values.map((value) => ({ value, name: pascal(value) }));
    assertUnique(id, members.map((m) => m.name));

    const lines: string[] = [];
    lines.push(...this.summary(id, 4));
    lines.push(`    public enum ${id}`);
    lines.push('    {');
    lines.push('        /// <summary>A value this client version does not know.</summary>');
    lines.push('        Unknown = 0,');
    members.forEach((m, i) => lines.push(`        ${m.name} = ${i + 1},`));
    lines.push('    }');
    lines.push('');
    lines.push(`    /// <summary>Wire strings for <see cref="${id}"/>.</summary>`);
    lines.push(`    public static class ${id}Wire`);
    lines.push('    {');
    lines.push(`        public static string ToWire(${id} value)`);
    lines.push('        {');
    lines.push('            switch (value)');
    lines.push('            {');
    for (const m of members) {
      lines.push(`                case ${id}.${m.name}: return ${literal(m.value)};`);
    }
    lines.push(`                default: throw new WireFormatException(${literal(id)}, "cannot send an unknown value");`);
    lines.push('            }');
    lines.push('        }');
    lines.push('');
    lines.push(`        public static ${id} FromWire(string value)`);
    lines.push('        {');
    lines.push('            switch (value)');
    lines.push('            {');
    for (const m of members) {
      lines.push(`                case ${literal(m.value)}: return ${id}.${m.name};`);
    }
    lines.push(`                default: return ${id}.Unknown;`);
    lines.push('            }');
    lines.push('        }');
    lines.push('    }');
    return lines.join('\n') + '\n';
  }

  // ------------------------------------------------------------------------
  // unions
  // ------------------------------------------------------------------------

  private indexUnion(id: string, variants: readonly JsonSchema[]): void {
    let discriminator: string | undefined;
    for (const variant of variants) {
      const name = this.refName(variant, `${id} variant`);
      const target = this.schema(name);
      const key = this.discriminatorOf(name, target);
      if (discriminator !== undefined && discriminator !== key) {
        throw new Error(`Union '${id}' mixes discriminators '${discriminator}' and '${key}'.`);
      }
      discriminator = key;
      if (this.unionOfVariant.has(name)) {
        throw new Error(`'${name}' is a variant of two unions.`);
      }
      this.unionOfVariant.set(name, id);
    }
    if (!discriminator) {
      throw new Error(`Union '${id}' has no variants.`);
    }
    this.discriminatorOfUnion.set(id, discriminator);
  }

  private discriminatorOf(name: string, schema: JsonSchema): string {
    for (const [key, property] of Object.entries(schema.properties ?? {})) {
      if (typeof property.const === 'string') {
        return key;
      }
    }
    throw new Error(`Union variant '${name}' has no string const discriminator.`);
  }

  private emitUnion(id: string, variants: readonly JsonSchema[]): string {
    const key = this.discriminatorOfUnion.get(id);
    if (!key) {
      throw new Error(`Union '${id}' was not indexed.`);
    }
    const lines: string[] = [];
    lines.push(...this.summary(id, 4));
    lines.push(`    public abstract partial class ${id} : IWireObject`);
    lines.push('    {');
    lines.push(`        /// <summary>The wire discriminator (<c>${key}</c>).</summary>`);
    lines.push(`        public abstract string ${pascal(key)} { get; }`);
    lines.push('');
    lines.push('        public abstract Dictionary<string, object> ToWire();');
    lines.push('');
    lines.push(`        public static ${id} FromWire(object? value)`);
    lines.push('        {');
    lines.push(`            var map = Wire.AsMap(value, ${literal(id)});`);
    lines.push(`            var discriminator = Wire.Required(map, ${literal(key)}, ${literal(id)}, Wire.AsString);`);
    lines.push('            switch (discriminator)');
    lines.push('            {');
    for (const variant of variants) {
      const name = this.refName(variant, id);
      lines.push(`                case ${name}.WireKind: return ${name}.FromWire(map);`);
    }
    lines.push(
      `                default: throw new WireFormatException(${literal(id)}, "unknown ${key} '" + discriminator + "'");`,
    );
    lines.push('            }');
    lines.push('        }');
    lines.push('    }');
    return lines.join('\n') + '\n';
  }

  // ------------------------------------------------------------------------
  // objects
  // ------------------------------------------------------------------------

  private emitObject(id: string, schema: JsonSchema): string {
    const union = this.unionOfVariant.get(id);
    const discriminator = union ? this.discriminatorOfUnion.get(union) : undefined;
    const required = new Set(schema.required ?? []);

    let wireKind: string | undefined;
    const properties: Property[] = [];
    for (const [wireName, property] of Object.entries(schema.properties ?? {})) {
      if (wireName === discriminator) {
        wireKind = property.const as string;
        continue;
      }
      const { ref, nullable } = this.resolve(property, `${id}.${wireName}`);
      const csName = pascal(wireName);
      if (csName === id) {
        throw new Error(`${id}.${wireName}: a C# member cannot share its type's name; rename the property.`);
      }
      const description = property.description;
      properties.push({
        wireName,
        csName,
        ref,
        required: required.has(wireName),
        nullable,
        ...(description === undefined ? {} : { description }),
      });
    }
    assertUnique(id, properties.map((p) => p.csName));

    const lines: string[] = [];
    lines.push(...this.summary(id, 4));
    lines.push(
      union
        ? `    public sealed partial class ${id} : ${union}`
        : `    public sealed partial class ${id} : IWireObject`,
    );
    lines.push('    {');

    if (union && discriminator && wireKind !== undefined) {
      lines.push(`        public const string WireKind = ${literal(wireKind)};`);
      lines.push('');
      lines.push(`        public override string ${pascal(discriminator)} => WireKind;`);
      lines.push('');
    }

    for (const p of properties) {
      if (p.description) {
        lines.push(`        /// <summary>${xml(p.description)}</summary>`);
      }
      lines.push(`        public ${this.propertyType(p)} ${p.csName} { get; set; }${this.initializer(p)}`);
      lines.push('');
    }

    // ---- ToWire ----
    lines.push(union ? '        public override Dictionary<string, object> ToWire()' : '        public Dictionary<string, object> ToWire()');
    lines.push('        {');
    lines.push(`            var map = new Dictionary<string, object>(${properties.length + (wireKind ? 1 : 0)});`);
    if (union && discriminator) {
      lines.push(`            map[${literal(discriminator)}] = WireKind;`);
    }
    for (const p of properties) {
      const optional = !p.required || p.nullable;
      if (optional) {
        const access = this.isValueType(p.ref) ? `${p.csName}.Value` : p.csName;
        lines.push(`            if (${p.csName} != null) map[${literal(p.wireName)}] = ${this.writer(p.ref, access)};`);
      } else {
        lines.push(`            map[${literal(p.wireName)}] = ${this.writer(p.ref, p.csName)};`);
      }
    }
    lines.push('            return map;');
    lines.push('        }');
    lines.push('');

    // ---- FromWire ----
    lines.push(
      union
        ? `        public static new ${id} FromWire(object? value)`
        : `        public static ${id} FromWire(object? value)`,
    );
    lines.push('        {');
    lines.push(`            var map = Wire.AsMap(value, ${literal(id)});`);
    if (union && discriminator && wireKind !== undefined) {
      lines.push(`            Wire.ExpectConst(map, ${literal(discriminator)}, WireKind, ${literal(id)});`);
    }
    lines.push(`            return new ${id}`);
    lines.push('            {');
    for (const p of properties) {
      lines.push(`                ${p.csName} = ${this.reader(id, p)},`);
    }
    lines.push('            };');
    lines.push('        }');
    lines.push('    }');
    return lines.join('\n') + '\n';
  }

  // ------------------------------------------------------------------------
  // type resolution
  // ------------------------------------------------------------------------

  private resolve(schema: JsonSchema, where: string): { ref: Ref; nullable: boolean } {
    // nullable forms: type: ['x', 'null'] or anyOf [x, {type:'null'}]
    if (Array.isArray(schema.type)) {
      const types = schema.type.filter((t) => t !== 'null');
      if (types.length !== 1) {
        throw new Error(`${where}: unions of primitive types are not supported.`);
      }
      return { ref: this.resolve({ ...schema, type: types[0] }, where).ref, nullable: schema.type.includes('null') };
    }
    if (schema.anyOf) {
      const nonNull = schema.anyOf.filter((s) => s.type !== 'null');
      const nullable = nonNull.length !== schema.anyOf.length;
      if (nonNull.length === 1 && nonNull[0]) {
        return { ref: this.resolve(nonNull[0], where).ref, nullable };
      }
      if (nonNull.every((s) => typeof s.const === 'number' && Number.isInteger(s.const))) {
        return { ref: { kind: 'int' }, nullable };
      }
      if (nonNull.every((s) => typeof s.const === 'string')) {
        return { ref: { kind: 'string' }, nullable };
      }
      throw new Error(`${where}: anyOf is only supported for nullability or literal sets.`);
    }
    if (schema.$ref) {
      const name = schema.$ref;
      const target = this.schema(name);
      if (this.isStringEnum(target)) return { ref: { kind: 'enum', name }, nullable: false };
      if (target.oneOf) return { ref: { kind: 'union', name }, nullable: false };
      if (this.isObject(target)) return { ref: { kind: 'object', name }, nullable: false };
      throw new Error(`${where}: $ref '${name}' is not an object, enum or union.`);
    }
    if (Object.keys(schema).filter((k) => k !== 'description' && k !== 'default').length === 0) {
      return { ref: { kind: 'any' }, nullable: true };
    }
    switch (schema.type) {
      case 'string':
        if (schema.enum) {
          throw new Error(`${where}: inline string enums are not allowed; register the enum with named().`);
        }
        return {
          ref: typeof schema.const === 'string' ? { kind: 'string', constValue: schema.const } : { kind: 'string' },
          nullable: false,
        };
      case 'integer': {
        const min = schema.minimum ?? -Number.MAX_SAFE_INTEGER;
        const max = schema.maximum ?? Number.MAX_SAFE_INTEGER;
        return { ref: min >= INT32_MIN && max <= INT32_MAX ? { kind: 'int' } : { kind: 'long' }, nullable: false };
      }
      case 'number':
        return { ref: { kind: 'double' }, nullable: false };
      case 'boolean':
        return { ref: { kind: 'bool' }, nullable: false };
      case 'array':
        if (!schema.items) throw new Error(`${where}: array without items.`);
        return { ref: { kind: 'list', item: this.resolve(schema.items, `${where}[]`).ref }, nullable: false };
      case 'object': {
        const hasProperties = schema.properties && Object.keys(schema.properties).length > 0;
        if (hasProperties) {
          throw new Error(`${where}: anonymous nested object; register it with named() so it has a C# name.`);
        }
        const additional = schema.additionalProperties;
        if (additional && typeof additional === 'object') {
          return { ref: { kind: 'map', value: this.resolve(additional, `${where}{}`).ref }, nullable: false };
        }
        throw new Error(`${where}: an empty inline object; use the registered Empty contract.`);
      }
      default:
        throw new Error(`${where}: unsupported schema ${JSON.stringify(schema)}.`);
    }
  }

  private csType(ref: Ref): string {
    switch (ref.kind) {
      case 'string': return 'string';
      case 'int': return 'int';
      case 'long': return 'long';
      case 'double': return 'double';
      case 'bool': return 'bool';
      case 'any': return 'object?';
      case 'enum':
      case 'object':
      case 'union': return ref.name;
      case 'list': return `List<${this.csType(ref.item)}>`;
      case 'map': return `Dictionary<string, ${this.csType(ref.value)}>`;
    }
  }

  private isValueType(ref: Ref): boolean {
    return ref.kind === 'int' || ref.kind === 'long' || ref.kind === 'double' || ref.kind === 'bool' || ref.kind === 'enum';
  }

  private propertyType(p: Property): string {
    const type = this.csType(p.ref);
    if (p.ref.kind === 'any') return type;
    return !p.required || p.nullable ? `${type}?` : type;
  }

  private initializer(p: Property): string {
    if (!p.required || p.nullable) return '';
    switch (p.ref.kind) {
      case 'string': return p.ref.constValue !== undefined ? ` = ${literal(p.ref.constValue)};` : ' = string.Empty;';
      case 'list': return ` = new ${this.csType(p.ref)}();`;
      case 'map': return ` = new ${this.csType(p.ref)}();`;
      case 'object': return ` = new ${p.ref.name}();`;
      case 'union': return ' = default!;';
      default: return '';
    }
  }

  /** An expression converting a C# value to its wire form. */
  private writer(ref: Ref, expr: string): string {
    switch (ref.kind) {
      case 'string':
      case 'int':
      case 'long':
      case 'double':
      case 'bool':
        return expr;
      case 'any':
        return `${expr}!`;
      case 'enum':
        return `${ref.name}Wire.ToWire(${expr})`;
      case 'object':
      case 'union':
        return `${expr}.ToWire()`;
      case 'list':
        return `Wire.ListToWire(${expr}, item => (object)${this.writer(ref.item, 'item')})`;
      case 'map':
        return `Wire.MapToWire(${expr}, item => (object)${this.writer(ref.value, 'item')})`;
    }
  }

  /** An expression of type Func<object?, string, T> converting a wire value at a path. */
  private converter(ref: Ref): string {
    switch (ref.kind) {
      case 'string': return 'Wire.AsString';
      case 'int': return 'Wire.AsInt';
      case 'long': return 'Wire.AsLong';
      case 'double': return 'Wire.AsDouble';
      case 'bool': return 'Wire.AsBool';
      case 'any': return 'Wire.AsAny';
      case 'enum': return `(v, path) => ${ref.name}Wire.FromWire(Wire.AsString(v, path))`;
      case 'object':
      case 'union': return `(v, path) => ${ref.name}.FromWire(v)`;
      case 'list': return `(v, path) => Wire.AsList(v, path, ${this.converter(ref.item)})`;
      case 'map': return `(v, path) => Wire.AsDictionary(v, path, ${this.converter(ref.value)})`;
    }
  }

  private reader(owner: string, p: Property): string {
    const path = literal(`${owner}.${p.wireName}`);
    const key = literal(p.wireName);
    const conv = this.converter(p.ref);
    if (p.required && !p.nullable) {
      return `Wire.Required(map, ${key}, ${path}, ${conv})`;
    }
    return this.isValueType(p.ref)
      ? `Wire.OptionalValue(map, ${key}, ${path}, ${conv})`
      : `Wire.OptionalRef(map, ${key}, ${path}, ${conv})`;
  }

  // ------------------------------------------------------------------------
  // helpers
  // ------------------------------------------------------------------------

  private schema(id: string): JsonSchema {
    const schema = this.schemas[id];
    if (!schema) throw new Error(`Unknown contract '${id}'.`);
    return schema;
  }

  private refName(schema: JsonSchema, where: string): string {
    if (!schema.$ref) throw new Error(`${where}: union variants must be registered contracts.`);
    return schema.$ref;
  }

  private isStringEnum(schema: JsonSchema): boolean {
    return schema.type === 'string' && Array.isArray(schema.enum);
  }

  private isObject(schema: JsonSchema): boolean {
    return schema.type === 'object';
  }

  private summary(id: string, indent: number): string[] {
    const text = this.docs.get(id)?.description;
    if (!text) return [];
    const pad = ' '.repeat(indent);
    return [`${pad}/// <summary>${xml(text)}</summary>`];
  }
}

function assertUnique(owner: string, names: readonly string[]): void {
  const seen = new Set<string>();
  for (const name of names) {
    if (seen.has(name)) throw new Error(`${owner}: two members map to the C# name '${name}'.`);
    seen.add(name);
  }
}

export { camel };
