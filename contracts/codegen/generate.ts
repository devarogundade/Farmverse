import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { z } from 'zod';
import { allContracts, contracts, CatalogueDoc, DEFAULT_CATALOGUE } from '../src';
import { CSharpEmitter, type ContractDoc, type JsonSchema } from './csharp';
import { emitManifest } from './manifest';

/**
 * `npm run gen`            write the generated C# into the Unity project
 * `npm run check`          fail (exit 1) if the generated C# is out of date
 *
 * Output: Assets/Farmverse/Runtime/Contracts/Generated/*.g.cs
 */

const NAMESPACE = 'Farmverse.Contracts';
const OUTPUT = resolve(__dirname, '../../Assets/Farmverse/Runtime/Contracts/Generated');

export function generate(): Map<string, string> {
  const json = z.toJSONSchema(contracts, { io: 'input', unrepresentable: 'throw', target: 'draft-2020-12' });
  const schemas = json.schemas as Record<string, JsonSchema>;

  const docs = new Map<string, ContractDoc>();
  for (const { id, schema } of allContracts()) {
    const meta = contracts.get(schema);
    docs.set(id, meta?.description === undefined ? { id } : { id, description: meta.description });
  }

  const files = new CSharpEmitter(schemas, docs, NAMESPACE).emitAll();
  files.set('Manifest.g.cs', emitManifest(NAMESPACE));
  files.set('CatalogueDefaults.g.cs', emitCatalogueDefaults());
  return new Map([...files.entries()].sort(([a], [b]) => a.localeCompare(b)));
}

/** The designed catalogue compiled into the client: what it plays with before (or without) the published copy. */
function emitCatalogueDefaults(): string {
  const json = JSON.stringify(CatalogueDoc.parse(DEFAULT_CATALOGUE));
  return [
    '// <auto-generated> contracts/src/catalogue.ts (DEFAULT_CATALOGUE) — do not edit; run `npm run contracts:gen`. </auto-generated>',
    '#nullable enable',
    `namespace ${NAMESPACE}`,
    '{',
    '    /// <summary>The catalogue as designed, for the first launch and offline play (the live copy is config/catalogue).</summary>',
    '    public static class CatalogueDefaults',
    '    {',
    `        public const int Version = ${DEFAULT_CATALOGUE.version};`,
    `        public const string Json = @"${json.replace(/"/g, '""')}";`,
    '    }',
    '}',
    '',
  ].join('\n');
}

function existing(dir: string): Map<string, string> {
  const result = new Map<string, string>();
  if (!existsSync(dir)) return result;
  for (const name of readdirSync(dir)) {
    if (name.endsWith('.g.cs')) result.set(name, readFileSync(join(dir, name), 'utf8'));
  }
  return result;
}

function main(): void {
  const check = process.argv.includes('--check');
  const wanted = generate();
  const current = existing(OUTPUT);

  const stale: string[] = [];
  for (const [name, content] of wanted) {
    if (current.get(name) !== content) stale.push(name);
  }
  const orphans = [...current.keys()].filter((name) => !wanted.has(name));

  if (check) {
    if (stale.length > 0 || orphans.length > 0) {
      console.error('Generated C# is out of date. Run `npm run contracts:gen`.');
      for (const name of stale) console.error(`  changed: ${name}`);
      for (const name of orphans) console.error(`  removed: ${name}`);
      process.exit(1);
    }
    console.log(`Generated C# is up to date (${wanted.size} files).`);
    return;
  }

  mkdirSync(OUTPUT, { recursive: true });
  for (const name of stale) writeFileSync(join(OUTPUT, name), wanted.get(name) ?? '', 'utf8');
  for (const name of orphans) {
    rmSync(join(OUTPUT, name));
    const meta = join(OUTPUT, `${name}.meta`);
    if (existsSync(meta)) rmSync(meta);
  }
  console.log(`Wrote ${stale.length} file(s), removed ${orphans.length}, ${wanted.size} total → ${OUTPUT}`);
}

if (require.main === module) {
  main();
}
