#!/usr/bin/env bash
# Deploys FARM, items and market to NEAR testnet under one account you own, in the order
# chain/README.md gives, and prints the settings the server, indexer and marketplace need.
#
#   MASTER=farmverse.testnet chain/scripts/deploy-testnet.sh
#
# Needs: near CLI (near-cli-rs) with MASTER's key in its keychain, chain/res/*.wasm
# (scripts/build.sh), curl, openssl, python3. MASTER needs about 13 testnet NEAR.
#
# Safe to re-run: accounts that exist are kept, and contracts that are initialised are skipped.
# Testnet only. The mainnet deploy is signed by the owner multisig, not by this script.
set -euo pipefail
cd "$(dirname "$0")/.."

: "${MASTER:?set MASTER to the testnet account that owns the contracts, e.g. farmverse.testnet}"
NETWORK=testnet
RPC=${RPC:-https://rpc.testnet.near.org}
OWNER=${OWNER:-$MASTER}                      # mainnet: the multisig
FARM_SUPPLY=${FARM_SUPPLY:-1000000000}       # whole FARM; the real total is still open (plan §11 Q1)
FEE_BPS=${FEE_BPS:-500}
ROYALTY_BPS=${ROYALTY_BPS:-250}
BASE_URI=${BASE_URI:-https://marketplace.farmverse.world/nft}
ENV_FILE=../backend/server/.env

FARM=farm.$MASTER
ITEMS=items.$MASTER
MARKET=market.$MASTER
TREASURY=treasury.$MASTER
STUDIO=studio.$MASTER

for f in res/farmverse_farm_token.wasm res/farmverse_items.wasm res/farmverse_market.wasm; do
  [[ -f $f ]] || { echo "missing $f: run scripts/build.sh first" >&2; exit 1; }
done
command -v near >/dev/null || { echo "near CLI not found: https://github.com/near/near-cli-rs" >&2; exit 1; }

rpc() { curl -fsS "$RPC" -H 'content-type: application/json' -d "$1"; }
final_height() { rpc '{"jsonrpc":"2.0","id":1,"method":"block","params":{"finality":"final"}}' | python3 -c 'import json,sys; print(json.load(sys.stdin)["result"]["header"]["height"])'; }
exists() { rpc "{\"jsonrpc\":\"2.0\",\"id\":1,\"method\":\"query\",\"params\":{\"request_type\":\"view_account\",\"finality\":\"final\",\"account_id\":\"$1\"}}" | grep -q '"result"'; }
has_code() { # an account without code has the all-ones hash
  rpc "{\"jsonrpc\":\"2.0\",\"id\":1,\"method\":\"query\",\"params\":{\"request_type\":\"view_account\",\"finality\":\"final\",\"account_id\":\"$1\"}}" |
    python3 -c 'import json,sys; r=json.load(sys.stdin).get("result"); sys.exit(0 if r and r["code_hash"] != "1"*32 else 1)'
}
view() { # contract method args → JSON result, or nothing
  local args; args=$(printf %s "$3" | base64 -w0)
  rpc "{\"jsonrpc\":\"2.0\",\"id\":1,\"method\":\"query\",\"params\":{\"request_type\":\"call_function\",\"finality\":\"final\",\"account_id\":\"$1\",\"method_name\":\"$2\",\"args_base64\":\"$args\"}}" |
    python3 -c 'import json,sys; r=json.load(sys.stdin).get("result"); print(bytes(r["result"]).decode()) if r and "result" in r else None'
}
call() { # contract method args deposit signer
  near contract call-function as-transaction "$1" "$2" json-args "$3" prepaid-gas '100.0 Tgas' attached-deposit "$4" \
    sign-as "$5" network-config "$NETWORK" sign-with-keychain send
}
sub() { # name NEAR
  if exists "$1"; then echo "• $1 exists"; return; fi
  echo "• creating $1 ($2 NEAR)"
  near account create-account fund-myself "$1" "$2 NEAR" autogenerate-new-keypair save-to-keychain \
    sign-as "$MASTER" network-config "$NETWORK" sign-with-keychain send
}
deploy() { # account wasm init-args
  if has_code "$1"; then echo "• $1 already has code: skipped (redeploy by hand if you mean to)"; return; fi
  echo "• deploying $2 to $1"
  near contract deploy "$1" use-file "$2" with-init-call new json-args "$3" prepaid-gas '100.0 Tgas' attached-deposit '0 NEAR' \
    network-config "$NETWORK" sign-with-keychain send
}

exists "$MASTER" || { echo "$MASTER doesn't exist on testnet (create it first)" >&2; exit 1; }

# ---------------------------------------------------------------- the game server's voucher key
touch "$ENV_FILE"
SEED=$(tr -d '' <"$ENV_FILE" | grep -E '^MINT_SIGNER_SEED=.+' | head -1 | cut -d= -f2- || true)
if [[ -z $SEED ]]; then
  SEED=$(openssl rand -base64 32)
  printf '\n# Testnet voucher signing key (generated by chain/scripts/deploy-testnet.sh)\nMINT_SIGNER_SEED=%s\n' "$SEED" >>"$ENV_FILE"
  echo "• generated MINT_SIGNER_SEED in backend/server/.env"
fi
# PKCS#8 header for a raw Ed25519 seed (as backend/server/src/mint/voucher.ts uses), then the seed.
SIGNER=$(python3 -c 'import sys; sys.stdout.buffer.write(bytes.fromhex("302e020100300506032b657004220420"))' | cat - <(printf %s "$SEED" | base64 -d) |
  openssl pkey -inform DER -pubout -outform DER | tail -c 32 |
  python3 -c '
import sys
raw = sys.stdin.buffer.read(); A = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz"
n = int.from_bytes(raw, "big"); out = ""
while n: n, r = divmod(n, 58); out = A[r] + out
print("ed25519:" + "1" * (len(raw) - len(raw.lstrip(b"\0"))) + out)')
echo "• voucher signer $SIGNER"

# ---------------------------------------------------------------- accounts
START=$(final_height)
sub "$FARM" 2.5
sub "$ITEMS" 4.5
sub "$MARKET" 3.5
sub "$TREASURY" 0.5
sub "$STUDIO" 1

# ---------------------------------------------------------------- contracts
SUPPLY_YOCTO="${FARM_SUPPLY}000000000000000000"
deploy "$FARM" res/farmverse_farm_token.wasm \
  "{\"treasury_id\":\"$TREASURY\",\"total_supply\":\"$SUPPLY_YOCTO\",\"metadata\":{\"spec\":\"ft-1.0.0\",\"name\":\"Farmverse\",\"symbol\":\"FARM\",\"decimals\":18}}"
deploy "$ITEMS" res/farmverse_items.wasm \
  "{\"owner_id\":\"$OWNER\",\"minter_id\":\"$STUDIO\",\"signers\":[\"$SIGNER\"],\"royalties\":{\"$TREASURY\":$ROYALTY_BPS},\"metadata\":{\"spec\":\"nft-1.0.0\",\"name\":\"Farmverse Items\",\"symbol\":\"FVITEM\",\"base_uri\":\"$BASE_URI\"}}"
deploy "$MARKET" res/farmverse_market.wasm \
  "{\"owner_id\":\"$OWNER\",\"ft_token_id\":\"$FARM\",\"treasury_id\":\"$TREASURY\",\"fee_bps\":$FEE_BPS,\"nft_contracts\":[\"$ITEMS\"]}"

# The market must hold FARM to settle sales (the treasury was registered by FARM's `new`).
if [[ $(view "$FARM" storage_balance_of "{\"account_id\":\"$MARKET\"}") == null ]]; then
  echo "• registering $MARKET with FARM"
  call "$FARM" storage_deposit "{\"account_id\":\"$MARKET\"}" '0.0125 NEAR' "$MASTER"
fi

# ---------------------------------------------------------------- checks
echo
echo "FARM:   $(view "$FARM" ft_metadata '{}')"
echo "items:  $(view "$ITEMS" get_config '{}')"
echo "market: $(view "$MARKET" get_config '{}')"

mkdir -p deploy
cat >deploy/testnet.env <<EOF
# Written by chain/scripts/deploy-testnet.sh on $(date -u +%FT%TZ)
NEAR_NETWORK=testnet
NEAR_ITEMS_CONTRACT=$ITEMS
NEAR_MARKET_CONTRACT=$MARKET
NEAR_FARM_CONTRACT=$FARM
NEAR_TREASURY=$TREASURY
NEAR_STUDIO=$STUDIO
INDEXER_START_BLOCK=$START
MINT_SIGNER_PUBLIC_KEY=$SIGNER
EOF

cat <<EOF

Done. Recorded in chain/deploy/testnet.env.

backend/server/.env:
  NEAR_ITEMS_CONTRACT=$ITEMS
  NEAR_MARKET_CONTRACT=$MARKET
  INDEXER_START_BLOCK=$START

web/marketplace/.env.local:
  VITE_ITEMS_CONTRACT=$ITEMS
  VITE_MARKET_CONTRACT=$MARKET
  VITE_FARM_CONTRACT=$FARM

Give a tester FARM:  MASTER=$MASTER chain/scripts/fund-tester.sh <account.testnet> <FARM>
EOF
